"""
Геометрия листовой детали: ПОЛИГОНАЛЬНЫЙ контур + честный расчёт развёртки.

==========================================================================
ЗАЧЕМ ЭТО ЗАМЕНЯЕТ СТАРУЮ МОДЕЛЬ
==========================================================================
Старая модель: Part(width, height) + прямоугольные вырезы. Она описывает
ПРЯМОУГОЛЬНИК. Я разобрал 37 настоящих развёрток мастера (DXF из КОМПАС):

    прямоугольников среди них        0 из 37
    отрезков в контуре одной детали  12 .. 54
    деталей с дугами/скруглениями    11 из 37

То есть старая модель не описывала НИ ОДНОЙ реальной детали. Отсюда и
"плоские непонятные" чертежи: программа рисовала прямоугольник там, где у
мастера ступенчатый контур с язычками и скруглениями.

==========================================================================
ГЛАВНОЕ: РАЗВЁРТКА СЧИТАЕТСЯ ЧЕРЕЗ ВЫЧЕТ НА ГИБ, А НЕ СЛОЖЕНИЕМ
==========================================================================
Старый add_flange() делал: развёртка = габарит + борт + борт.
Это НЕВЕРНО и давало брак.

Деталь "Дно" (К 01.01.01.007), реальная развёртка мастера: 495.0 мм.
Старая формула дала бы: 457 + 20 + 20 = 497.0 мм. Ошибка 2 мм НА КАЖДОМ
гибе, и она копится: на детали с 4 бортами - до 8 мм.

Металл при гибке ВЫТЯГИВАЕТСЯ: наружный радиус растягивается, внутренний
сжимается, а длина сохраняется только по НЕЙТРАЛЬНОЙ ЛИНИИ. Поэтому
плоская заготовка КОРОЧЕ суммы сторон на величину "вычета на гиб" (bend
deduction, BD).

    развёртка = сумма_плоских_участков + сумма_припусков_на_гиб
    BD (вычет) = 2*(R + S) - BA
    BA (припуск) = (угол_рад) * (R + K*S)

где R - внутренний радиус гиба, S - толщина, K - K-фактор (положение
нейтральной линии, доля от толщины).

==========================================================================
ОТКУДА ВЗЯТ BD = 2.2 мм (это КАЛИБРОВКА ПО МАСТЕРУ, не выдумка)
==========================================================================
В развёртках мастера борт 20 мм устойчиво даёт плоский участок 17.80 мм
(встречается 26 раз по всему комплекту при S=1). Значит:

    BD(S=1, 90°) = 20.0 - 17.8 = 2.2 мм

Это ИЗМЕРЕННЫЙ факт из его DXF, а не подгонка. Пара (R, K) по одному
уравнению однозначно не находится (много решений дают BD=2.2), поэтому
модель хранит именно то, что реально известно - таблицу BD по толщине,
- и проверяется автотестом против DXF мастера (tests/test_reference.py).

Если цех сменит станок/оснастку - правится ОДНА таблица BEND_DEDUCTION,
и всё пересчитается. Значения для S!=1 помечены как НЕ ПРОВЕРЕННЫЕ: в
референсе гнутые детали только S=1 (детали S=2 - плоские накладки).
"""
import math

# --- Калибровка по развёрткам мастера (см. шапку) ---
# Ключ: (толщина, угол в градусах) -> вычет на гиб, мм
BEND_DEDUCTION = {
    (1.0, 90): 2.2,     # ИЗМЕРЕНО: борт 20.0 -> плоский участок 17.8 (x26 в комплекте)
}

# Для толщин, которых нет в таблице, считаем по формуле с этими параметрами.
# ВНИМАНИЕ: не проверено против мастера (в его комплекте гнут только S=1).
DEFAULT_K = 0.40      # K-фактор (нейтральная линия)
DEFAULT_R_RATIO = 1.2  # внутренний радиус гиба = R_RATIO * S


def bend_deduction(thickness, angle=90.0):
    """
    Вычет на гиб, мм. Сначала - калиброванная таблица по мастеру,
    иначе - расчёт по K-фактору.
    """
    key = (round(thickness, 2), int(round(angle)))
    if key in BEND_DEDUCTION:
        return BEND_DEDUCTION[key]

    S = thickness
    R = DEFAULT_R_RATIO * S
    a = math.radians(angle)
    BA = a * (R + DEFAULT_K * S)
    BD = 2 * (R + S) * math.tan(a / 2) - BA
    return BD


def flat_length(segments, thickness, angles=None):
    """
    Длина развёртки цепочки плоских участков, соединённых гибами.

    segments: длины ГОТОВЫХ (согнутых) участков по наружному габариту
    angles:   углы гибов между ними (по умолчанию 90°), len = len(segments)-1

    Пример (дно с двумя бортами по 20 при корпусе 457, S=1):
        flat_length([20, 457, 20], 1.0) -> 457 + 2*(20 - 2.2) = 492.6
    """
    if not segments:
        return 0.0
    n_bends = len(segments) - 1
    if angles is None:
        angles = [90.0] * n_bends
    total = sum(segments)
    for a in angles:
        total -= bend_deduction(thickness, a)
    return total


class Contour:
    """
    Плоский контур детали как ПОЛИГОН (а не прямоугольник).

    points: [(x, y), ...] - вершины замкнутого контура, мм, от левого
            нижнего угла заготовки
    holes:  [[(x,y), ...], ...] - замкнутые внутренние контуры (вырезы
            произвольной формы, не только прямоугольник/круг)
    arcs:   [(cx, cy, r, a1, a2), ...] - скругления/дуги, градусы

    Именно так устроены настоящие детали мастера, поэтому модель обязана
    уметь это, а не только w x h.
    """

    def __init__(self, points=None, holes=None, arcs=None):
        self.points = list(points or [])
        self.holes = [list(h) for h in (holes or [])]
        self.arcs = list(arcs or [])

    # --- габариты ---

    @property
    def bbox(self):
        xs = [p[0] for p in self.points]
        ys = [p[1] for p in self.points]
        for cx, cy, r, a1, a2 in self.arcs:
            xs += [cx - r, cx + r]
            ys += [cy - r, cy + r]
        if not xs:
            return (0, 0, 0, 0)
        return (min(xs), min(ys), max(xs), max(ys))

    @property
    def width(self):
        x0, y0, x1, y1 = self.bbox
        return x1 - x0

    @property
    def height(self):
        x0, y0, x1, y1 = self.bbox
        return y1 - y0

    @property
    def area(self):
        """Площадь полигона (формула шнурования) минус вырезы, м²"""
        def poly_area(pts):
            s = 0.0
            for i in range(len(pts)):
                x1, y1 = pts[i]
                x2, y2 = pts[(i + 1) % len(pts)]
                s += x1 * y2 - x2 * y1
            return abs(s) / 2.0

        a = poly_area(self.points) if len(self.points) >= 3 else 0.0
        for h in self.holes:
            if len(h) >= 3:
                a -= poly_area(h)
        return a / 1_000_000.0

    # --- конструкторы ---

    @staticmethod
    def rect(w, h, x=0.0, y=0.0):
        return Contour([(x, y), (x + w, y), (x + w, y + h), (x, y + h)])

    def add_rect_hole(self, cx, cy, w, h):
        self.holes.append([
            (cx - w / 2, cy - h / 2), (cx + w / 2, cy - h / 2),
            (cx + w / 2, cy + h / 2), (cx - w / 2, cy + h / 2),
        ])
        return self

    def add_round_hole(self, cx, cy, r, segments=24):
        pts = [(cx + r * math.cos(2 * math.pi * i / segments),
                cy + r * math.sin(2 * math.pi * i / segments))
               for i in range(segments)]
        self.holes.append(pts)
        return self

    def translate(self, dx, dy):
        self.points = [(x + dx, y + dy) for x, y in self.points]
        self.holes = [[(x + dx, y + dy) for x, y in h] for h in self.holes]
        self.arcs = [(cx + dx, cy + dy, r, a1, a2)
                     for cx, cy, r, a1, a2 in self.arcs]
        return self

    def normalize(self):
        """Сдвинуть контур так, чтобы левый нижний угол был в (0,0)"""
        x0, y0, _, _ = self.bbox
        return self.translate(-x0, -y0)

    def __repr__(self):
        return (f"<Contour {self.width:.1f}x{self.height:.1f} "
                f"точек={len(self.points)} вырезов={len(self.holes)} "
                f"дуг={len(self.arcs)}>")


def build_flanged_box_blank(inner_w, inner_d, flange, thickness,
                            relief=2.51, tabs=None):
    """
    Развёртка "коробки" - детали с бортами по всем 4 сторонам
    (дно, крышка, корпус ящика). Это САМЫЙ частый тип у мастера.

    inner_w/inner_d: размеры ГОТОВОГО дна (между бортами)
    flange:          высота борта (номинал, напр. 20)
    relief:          зазор угловой разделительной прорези (у мастера 2.51)

    Возвращает Contour развёртки: центральное поле + 4 лепестка-борта,
    углы вырезаны (иначе металл рвётся при гибке).

    ВАЖНО: длина лепестка = flange - BD (вычет на гиб), а НЕ flange.
    Именно здесь старая модель врала.
    """
    f = flange - bend_deduction(thickness, 90)   # плоская длина борта
    W, D = inner_w, inner_d
    g = relief / 2.0

    pts = [
        # нижняя кромка
        (f + g, 0), (f + W - g, 0),
        (f + W - g, f), (f + W, f),
        # правая кромка
        (f + W, f + g), (f + W + f, f + g),
        (f + W + f, f + D - g), (f + W, f + D - g),
        (f + W, f + D), (f + W - g, f + D),
        # верхняя кромка
        (f + W - g, f + D + f), (f + g, f + D + f),
        (f + g, f + D), (f, f + D),
        # левая кромка
        (f, f + D - g), (0, f + D - g),
        (0, f + g), (f, f + g),
        (f, f), (f + g, f),
    ]
    return Contour(pts)