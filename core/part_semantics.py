# Внутренние детали, которые почти по определению не видны, даже если
# конкретной роли нет в таблице выше (страховка для новых билдеров).
_HIDDEN_KEYWORDS = ("полка", "дно", "задняя", "перегородка", "усилитель", "направляющая")


def _normalize(name):
    """Привести имя детали к роли: убрать префикс модуля и уточнение в скобках.

    '[Шкаф под мойку] Крыша (вырез под мойку)' -> 'крыша'
    """
    s = name.strip()
    if s.startswith("["):          # префикс модуля из KitchenProject.parts
        close = s.find("]")
        if close != -1:
            s = s[close + 1:].strip()
    if "(" in s:                   # уточнение вида "Крыша (вырез под мойку)"
        s = s.split("(", 1)[0].strip()
    return s.lower()


def _lookup(name):
    """Найти спецификацию роли: сперва точное совпадение, затем по префиксу.

    'Полка внутренняя' -> роль 'полка'; 'Дно ящика' -> роль 'дно'.
    Без этого любое уточнение в названии ('Полка нижняя', 'Боковина ящика')
    промахивалось мимо таблицы, и деталь уходила в документацию без
    пояснения и без флага скрытости.
    Префиксы сортируем по длине убыв., чтобы 'боковина с вентиляцией'
    выигрывала у 'боковина'.
    """
    role = _normalize(name)
    if role in _ROLE_SPECS:
        return _ROLE_SPECS[role]
    for key in sorted(_ROLE_SPECS, key=len, reverse=True):
        if role.startswith(key + " ") or role == key:
            return _ROLE_SPECS[key]
    return None


def describe(name):
    """Текстовое пояснение к детали по её имени. '' если роль неизвестна."""
    spec = _lookup(name)
    return spec[0] if spec else ""


def is_hidden(name):
    """Скрыта ли деталь в собранном изделии (по роли)."""
    spec = _lookup(name)
    if spec:
        return spec[1]
    role = _normalize(name)
    return any(kw in role for kw in _HIDDEN_KEYWORDS)


def annotate(part):
    """
    Проставить детали description и is_hidden_in_assembly по её роли,
    НЕ затирая то, что уже заполнено явно (билдером или конструктором в UI).

    ВАЖНО про "не задано": для флага скрытости признак этого - None, а НЕ
    False. Если проверять через `if not part.is_hidden_in_assembly`, то
    явно выставленное False (деталь видна) неотличимо от "никто не заполнял"
    и будет молча затёрто правилом по роли. На открытой полке-рейлинге это
    ровно так и происходило: билдер ставил False, annotate возвращал True.

    Меняет part на месте и возвращает его же.
    """
    if not part.description:
        part.description = describe(part.name)
    if part.is_hidden_in_assembly is None:
        part.is_hidden_in_assembly = is_hidden(part.name)
    return part


